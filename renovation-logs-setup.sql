-- Supabase SQL Editor: create the live text-based renovation log table.
-- Replace every YOUR_ADMIN_USER_UUID below with the UUID shown under
-- Authentication -> Users for your admin account, then run this entire script.
-- Never put a service_role/secret key in the website.

create table if not exists public.renovation_logs (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  log_date date not null default current_date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.renovation_logs enable row level security;

grant select on public.renovation_logs to anon, authenticated;
grant insert, update, delete on public.renovation_logs to authenticated;
grant usage, select on sequence public.renovation_logs_id_seq to authenticated;

drop policy if exists "Anyone can read renovation logs" on public.renovation_logs;
create policy "Anyone can read renovation logs"
  on public.renovation_logs for select to anon, authenticated using (true);

drop policy if exists "Admin can create renovation logs" on public.renovation_logs;
create policy "Admin can create renovation logs"
  on public.renovation_logs for insert to authenticated
  with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

drop policy if exists "Admin can update renovation logs" on public.renovation_logs;
create policy "Admin can update renovation logs"
  on public.renovation_logs for update to authenticated
  using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid)
  with check (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);

drop policy if exists "Admin can delete renovation logs" on public.renovation_logs;
create policy "Admin can delete renovation logs"
  on public.renovation_logs for delete to authenticated
  using (auth.uid() = 'YOUR_ADMIN_USER_UUID'::uuid);
